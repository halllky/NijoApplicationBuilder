import React from "react"
import * as ReactRouter from "react-router-dom"
import { useNavigate } from "react-router-dom"
import { Controller, type UseFormReturn } from "react-hook-form"
import { SearchPageBase, SortComboItem } from "../layout/SearchPageBase"
import { FormLabel } from "../layout/FormLabel"
import { WordTextBox } from "../input/WordTextBox"
import { DateInput } from "../input/DateInput"
import { NumericTextBox } from "../input/NumericTextBox"
import { DataTableColumn, NumericCell } from "../layout/DataTable"
import { numericPropsOf } from "../util/fieldMetadata"
import { 売上一覧SearchCondition, createNew売上一覧SearchCondition, 売上一覧DisplayData } from "../__autoGenerated/売上一覧"
import { Link } from "react-router-dom"
import { getLinkUrlToP101売上詳細 } from "./P101_売上詳細"

export const URL = "/uriage"

/**
 * P100_売上 へ遷移するためのフック
 */
export function useNavigateToP100売上() {
  const navigate = useNavigate()
  return React.useCallback(() => {
    navigate(URL)
  }, [navigate])
}

/**
 * ルーティング定義
 */
export default {
  path: URL,
  element: <P100_売上 />,
  loader: undefined,
} satisfies ReactRouter.RouteObject

/**
 * P100 売上
 */
function P100_売上() {
  const sortOptions = React.useMemo((): SortComboItem<"売上一覧">[] => [
    { key: '売上一覧.売上SEQ', label: '売上SEQ' },
    { key: '売上一覧.売上日時', label: '売上日時' },
    { key: '売上一覧.担当者.従業員Ref.従業員番号', label: '担当者' },
    { key: '売上一覧.担当者.従業員Ref.氏名', label: '担当者氏名' },
    { key: '売上一覧.備考', label: '備考' },
    // SQLite はdecimalのソートができない
    // { key: '売上一覧.売上総額_税込', label: '売上総額(税込)' },
    { key: '売上一覧.売上数量合計', label: '売上数量合計' },
  ], [])

  const createInitialCondition = React.useCallback((): 売上一覧SearchCondition => ({
    ...createNew売上一覧SearchCondition(),
    sort: ['売上一覧.売上日時（降順）'],
  }), [])

  return (
    <SearchPageBase
      queryModelType="売上一覧"
      pageTitle="売上"
      searchConditionDefaultSize={160}
      sortOptions={sortOptions}
      createInitialCondition={createInitialCondition}
      header={(
        <Link to={getLinkUrlToP101売上詳細()} className="text-teal-600 underline">
          新規登録
        </Link>
      )}
      renderSearchCondition={SearchCondition}
      defineSearchResultColumns={[() => [
        {
          header: '',
          widthPx: 60,
          render: row => (
            <Link
              className="text-sky-600 underline"
              to={getLinkUrlToP101売上詳細(row.売上SEQ)}>
              詳細
            </Link>
          ),
        },
        { header: '売上SEQ', render: row => row.売上SEQ },
        { header: '売上日時', render: row => row.売上日時 },
        { header: '担当者', widthPx: 96, render: row => row.担当者.従業員番号 },
        { header: '', widthPx: 144, render: row => row.担当者.氏名 },
        { header: '売上総額(税込)', widthPx: 136, render: row => <NumericCell value={row.合計金額} suffix="円" /> },
        { header: '売上数量合計', widthPx: 120, render: row => <NumericCell value={row.売上数量合計} suffix="個" /> },
        { header: '備考', widthPx: 300, render: row => row.備考 },
      ] satisfies DataTableColumn<売上一覧DisplayData>[], []]}
    />
  )
}

function SearchCondition({ register, control, setFocus }: UseFormReturn<売上一覧SearchCondition>): React.ReactNode {

  React.useEffect(() => {
    setFocus("filter.売上SEQ")
  }, [setFocus])

  return (
    <div className="h-full py-1 flex flex-col lg:flex-row lg:items-start gap-x-8 gap-y-2">

      {/* 左列 */}
      <div className="grid grid-cols-[112px_360px] gap-2">

        <FormLabel className="text-right">売上SEQ</FormLabel>
        <Controller
          name="filter.売上SEQ"
          control={control}
          render={({ field: { name, value, onChange, onBlur, ref } }) => (
            <div className="flex items-center gap-2" onBlur={onBlur}>
              <NumericTextBox name={`${name}.from`} ref={ref}
                {...numericPropsOf("売上一覧", "売上SEQ")}
                value={value?.from ?? ""}
                onChange={e => onChange({ ...value, from: e.target.value })} />
              <span>～</span>
              <NumericTextBox name={`${name}.to`}
                {...numericPropsOf("売上一覧", "売上SEQ")}
                value={value?.to ?? ""}
                onChange={e => onChange({ ...value, to: e.target.value })} />
            </div>
          )}
        />

        <FormLabel className="text-right">売上日時</FormLabel>
        <Controller
          name="filter.売上日時"
          control={control}
          render={({ field: { name, value, onChange, onBlur, ref } }) => (
            <div className="flex items-center gap-2" onBlur={onBlur}>
              {/* 売上日時は時刻までもっているので既定ではdatetimeになるが、検索するときは日付程度のことが多いのでdateにする */}
              <DateInput appearance="date" name={`${name}.from`} ref={ref}
                value={value?.from ?? ""}
                onChange={e => onChange({ ...value, from: e.target.value })} />
              <span>～</span>
              <DateInput appearance="date" name={`${name}.to`}
                value={value?.to ?? ""}
                onChange={e => onChange({ ...value, to: e.target.value })} />
            </div>
          )}
        />

        <FormLabel className="text-right">担当者</FormLabel>
        <div className="flex gap-2">
          <WordTextBox {...register("filter.担当者.従業員番号")} placeholder="従業員番号" className="w-1/3" />
          <WordTextBox {...register("filter.担当者.氏名")} placeholder="氏名" className="flex-1" />
        </div>
      </div>

      {/* 右列 */}
      <div className="grid grid-cols-[112px_360px] gap-2">

        <FormLabel className="text-right">備考</FormLabel>
        <WordTextBox {...register("filter.備考")} />

        <FormLabel className="text-right">売上総額(税込)</FormLabel>
        <Controller
          name="filter.合計金額"
          control={control}
          render={({ field: { name, value, onChange, onBlur, ref } }) => (
            <div className="flex items-center gap-2" onBlur={onBlur}>
              <NumericTextBox name={`${name}.from`} ref={ref}
                {...numericPropsOf("売上一覧", "合計金額")}
                value={value?.from ?? ""}
                onChange={e => onChange({ ...value, from: e.target.value })} />
              <span>～</span>
              <NumericTextBox name={`${name}.to`}
                {...numericPropsOf("売上一覧", "合計金額")}
                value={value?.to ?? ""}
                onChange={e => onChange({ ...value, to: e.target.value })} />
            </div>
          )}
        />

        <FormLabel className="text-right">売上数量合計</FormLabel>
        <Controller
          name="filter.売上数量合計"
          control={control}
          render={({ field: { name, value, onChange, onBlur, ref } }) => (
            <div className="flex items-center gap-2" onBlur={onBlur}>
              <NumericTextBox name={`${name}.from`} ref={ref}
                {...numericPropsOf("売上一覧", "売上数量合計")}
                value={value?.from ?? ""}
                onChange={e => onChange({ ...value, from: e.target.value })} />
              <span>～</span>
              <NumericTextBox name={`${name}.to`}
                {...numericPropsOf("売上一覧", "売上数量合計")}
                value={value?.to ?? ""}
                onChange={e => onChange({ ...value, to: e.target.value })} />
            </div>
          )}
        />
      </div>
    </div>
  )
}
