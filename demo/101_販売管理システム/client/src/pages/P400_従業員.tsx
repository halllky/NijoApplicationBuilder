/**
 * P400 従業員
 */
function P400_従業員() {
  // 検索条件
  const searchConditionMethods = useForm<従業員マスタSearchCondition>({
    defaultValues: createNew従業員マスタSearchCondition()
  })
  const { register: searchRegister, handleSubmit: handleSearchSubmit } = searchConditionMethods

  // 編集用データ（検索結果が入る）
  const [key, setKey] = React.useState(0) // フォーム再生成用
  const [defaultValues, setDefaultValues] = React.useState<従業員一括更新ParameterDisplayData>(() => createNew従業員一括更新ParameterDisplayData())
  const methods = useForm<従業員一括更新ParameterDisplayData>({
    defaultValues
  })
  const [saving, setSaving] = React.useState(false)

  // defaultValues が更新されたらフォームをリセット
  React.useEffect(() => {
    methods.reset(defaultValues)
  }, [defaultValues, methods])

  // 検索実行
  const onSearch = React.useCallback(async (condition: 従業員マスタSearchCondition) => {
    const result = await callComplexPostEndpointAsync('従業員マスタ', condition, {
      ignoreConfirm: true,
    })
    if (result.type === 'ok') {
      const newData = createNew従業員一括更新ParameterDisplayData()
      newData.更新対象従業員一覧 = result.returnValue.currentPageItems.map(item => {
        const row = createNew更新対象従業員一覧DisplayData()
        row.従業員 = item
        row.existsInDatabase = true
        row.willBeChanged = false // 初期ロード時は変更なし扱い（必要であれば後で監視）
        return row
      })
      setDefaultValues(newData)
      setKey(prev => prev + 1)
    }
  }, [])

  React.useEffect(() => {
    // 初期表示時に空条件で検索実行
    const initialCondition = createNew従業員マスタSearchCondition()
    onSearch(initialCondition)
  }, [onSearch])

  // 保存実行
  const { replaceMessages, clearMessages } = DetailMessage.useSetter()
  const handleSave = React.useCallback(async () => {
    try {
      clearMessages()
      setSaving(true)
      const data = toWillBeChangedApplied(defaultValues, methods.getValues(), deepEqual従業員一括更新Parameter)

      // 従業員一括更新コマンドの呼び出し
      const result = await callComplexPostEndpointAsync('従業員一括更新', data)

      if (result.type === 'ok') {
        // 保存成功後、再検索して最新状態（Version等）を反映
        replaceMessages(result.detail)
        const currentCondition = searchConditionMethods.getValues()
        await onSearch(currentCondition)
      } else if (result.type === 'canceled') {
        // 何もしない
      } else {
        replaceMessages(result.detail)
      }
    } finally {
      setSaving(false)
    }
  }, [defaultValues, onSearch, searchConditionMethods, methods, replaceMessages, clearMessages])

  return (
    <PageBase
      browserTitle="従業員"
      isDirty={methods.formState.isDirty}
      className="gap-2 px-8 py-2"
      header={(
        <>
          <PageTitle>従業員</PageTitle>
          <div className="flex-1"></div>
          <Button fill loading={saving} onClick={handleSave}>保存</Button>
        </>
      )}
      contents={(
        <div className="flex-1 flex flex-col gap-4">
          {/* 検索条件エリア */}
          <div className="border p-2 rounded bg-gray-50">
            <h2 className="font-bold mb-2">検索条件</h2>
            <div className="flex gap-4 items-end">
              <div>
                <FormLabel>氏名</FormLabel>
                <WordTextBox {...searchRegister("filter.氏名")} maxLength={maxLengthOf("従業員マスタ", "氏名")} />
              </div>
              <div>
                <Button outline onClick={handleSearchSubmit(onSearch)}>検索</Button>
              </div>
            </div>
          </div>

          {/* 一覧編集エリア */}
          <div className="flex-1 min-h-0">
            <EmployeeGrid methods={methods} />
          </div>
        </div>
      )}
    />
  )
}

function EmployeeGrid({ methods }: { methods: UseFormReturn<従業員一括更新ParameterDisplayData> }) {
  const maxLen従業員番号 = maxLengthOf("従業員マスタ", "従業員番号")
  const maxLen氏名 = maxLengthOf("従業員マスタ", "氏名")

  // 列定義（下の useFieldArrayForEditableGrid2 呼び出しの中）から remove を呼べるようにするための ref。
  // 同一文の中で自分自身の戻り値（remove）を参照すると型推論が循環してしまうため、
  // 呼び出しより前に宣言した ref 経由で間接的に参照する。
  const removeRef = React.useRef<(index: number) => void>(() => { })

  const {
    fieldArrayReturn: { append, remove },
    editableGrid2Props,
  } = Grid.useFieldArrayForEditableGrid2(
    {
      name: "更新対象従業員一覧",
      control: methods.control,
      getValues: methods.getValues,
      setValue: methods.setValue,
    },
    helper => [
      // 操作列（削除・復元）。既にDBにある行は論理削除（willBeDeletedフラグ）、新規行は物理削除。
      helper.button(
        row => row.willBeDeleted ? "復元" : "削除",
        (row, rowIndex) => {
          if (row.willBeDeleted) {
            methods.setValue(`更新対象従業員一覧.${rowIndex}.willBeDeleted`, false)
          } else if (row.existsInDatabase) {
            methods.setValue(`更新対象従業員一覧.${rowIndex}.willBeDeleted`, true)
          } else {
            removeRef.current(rowIndex)
          }
        },
        { defaultWidth: 64, disableResizing: true, isFixed: true },
      ),
      helper.text("従業員番号", "従業員.従業員番号", {
        defaultWidth: 160,
        maxLength: maxLen従業員番号,
        isReadOnly: row => !!row.existsInDatabase,
      }),
      helper.text("氏名", "従業員.氏名", { defaultWidth: 240, maxLength: maxLen氏名 }),
      helper.checkBox("入荷担当", "従業員.入荷担当", { defaultWidth: 88 }),
      helper.checkBox("販売担当", "従業員.販売担当", { defaultWidth: 88 }),
      helper.checkBox("管理者", "従業員.システム管理者", { defaultWidth: 88 }),
      helper.detailMessage({ defaultWidth: 320 }),
    ],
    [],
  )
  removeRef.current = remove

  // 行追加
  const handleAdd = () => {
    append(createNew更新対象従業員一覧DisplayData())
  }

  return (
    <div className="h-full flex flex-col gap-2">
      <div>
        <Button outline mini onClick={handleAdd}>＋ 行追加</Button>
      </div>
      <Grid.EG2.EditableGrid2
        {...editableGrid2Props}
        // 論理削除された行はグリッド全体を読み取り専用にする（削除・復元ボタン自体は disableIfReadOnly を付けていないため操作可能）
        isReadOnly={row => row.willBeDeleted === true}
        getRowClassName={row => row.willBeDeleted ? "bg-red-50 opacity-60" : ""}
        className="flex-1 border border-gray-300"
      />
    </div>
  )
}

