import React from "react"
import * as ReactRouter from "react-router-dom"
import { useNavigate, Link } from "react-router-dom"
import { SearchPageBase, SortComboItem } from "../layout/SearchPageBase"
import { FormLabel } from "../layout/FormLabel"
import { WordTextBox } from "../input/WordTextBox"
import { DateInput } from "../input/DateInput"
import { NumericTextBox } from "../input/NumericTextBox"
import { DataTableColumn, NumericCell } from "../layout/DataTable"
import { numericPropsOf, maxLengthOf } from "../util/fieldMetadata"
import { 入荷一覧SearchCondition, createNew入荷一覧SearchCondition, 入荷一覧DisplayData } from "../__autoGenerated/入荷一覧"
import { getLinkUrlToP201入荷詳細 } from "./P201_入荷詳細"
import { RefTo従業員SearchCondition } from "../input/search-dialog/RefTo従業員"
import { Controller, UseFormReturn } from "react-hook-form"

export const URL = "/nyuka"

/**
 * P200_入荷 へ遷移するためのフック
 */
export function useNavigateToP200入荷() {
  const navigate = useNavigate()
  return React.useCallback(() => {
    navigate(URL)
  }, [navigate])
}

/**
 * ルーティング定義
 */
export default {
  path: URL,
  element: <P200_入荷 />,
  loader: undefined,
} satisfies ReactRouter.RouteObject

/**
 * P200 入荷
 */
function P200_入荷() {
  const sortOptions = React.useMemo((): SortComboItem<"入荷一覧">[] => [
    { key: '入荷一覧.入荷ID', label: '入荷ID' },
    { key: '入荷一覧.入荷日時', label: '入荷日時' },
    { key: '入荷一覧.担当者.従業員Ref.従業員番号', label: '担当者' },
    { key: '入荷一覧.担当者.従業員Ref.氏名', label: '担当者氏名' },
    { key: '入荷一覧.備考', label: '備考' },
    { key: '入荷一覧.明細件数', label: '明細件数' },
    { key: '入荷一覧.入荷数量合計', label: '入荷数量合計' },
  ], [])

  const createInitialCondition = React.useCallback((): 入荷一覧SearchCondition => ({
    ...createNew入荷一覧SearchCondition(),
    sort: ['入荷一覧.入荷日時（降順）'],
  }), [])

  return (
    <SearchPageBase
      queryModelType="入荷一覧"
      pageTitle="入荷"
      searchConditionDefaultSize={160}
      sortOptions={sortOptions}
      createInitialCondition={createInitialCondition}
      header={(
        <Link to={getLinkUrlToP201入荷詳細()} className="text-teal-600 underline">
          新規登録
        </Link>
      )}
      renderSearchCondition={SearchCondition}
      defineSearchResultColumns={[() => [
        {
          header: '',
          widthPx: 60,
          render: row => (
            <Link
              className="text-sky-600 underline"
              to={getLinkUrlToP201入荷詳細(row.入荷ID)}>
              詳細
            </Link>
          ),
        },
        { header: '入荷ID', widthPx: 180, render: row => row.入荷ID },
        { header: '入荷日時', render: row => row.入荷日時 },
        { header: '担当者', widthPx: 96, render: row => row.担当者.従業員番号 },
        { header: '', widthPx: 144, render: row => row.担当者.氏名 },
        { header: '明細件数', widthPx: 96, render: row => <NumericCell value={row.明細件数} /> },
        { header: '入荷数量合計', widthPx: 120, render: row => <NumericCell value={row.入荷数量合計} suffix="個" /> },
        { header: '備考', widthPx: 300, render: row => row.備考 },
      ] satisfies DataTableColumn<入荷一覧DisplayData>[], []]}
    />
  )
}

function SearchCondition({ register, control, setFocus }: UseFormReturn<入荷一覧SearchCondition>): React.ReactNode {

  React.useEffect(() => {
    setFocus("filter.入荷ID")
  }, [setFocus])

  return (
    <div className="h-full py-1 flex flex-col lg:flex-row lg:items-start gap-x-8 gap-y-2">

      {/* 左列 */}
      <div className="grid grid-cols-[112px_360px] gap-2">

        <FormLabel className="text-right">入荷ID</FormLabel>
        <WordTextBox {...register("filter.入荷ID")} maxLength={maxLengthOf("入荷一覧", "入荷ID")} />

        <FormLabel className="text-right">入荷日時</FormLabel>
        <Controller
          name="filter.入荷日時"
          control={control}
          render={({ field: { name, value, onChange, onBlur, ref } }) => (
            <div className="flex items-center gap-2" onBlur={onBlur}>
              {/* 入荷日時は時刻までもっているので既定ではdatetimeになるが、検索するときは日付程度のことが多いのでdateにする */}
              <DateInput appearance="date" name={`${name}.from`} ref={ref}
                value={value?.from ?? ""}
                onChange={e => onChange({ ...value, from: e.target.value })} />
              <span>～</span>
              <DateInput appearance="date" name={`${name}.to`}
                value={value?.to ?? ""}
                onChange={e => onChange({ ...value, to: e.target.value })} />
            </div>
          )}
        />

        <FormLabel className="text-right">担当者</FormLabel>
        <RefTo従業員SearchCondition
          name="filter.担当者"
          control={control}
        />
      </div>

      {/* 右列 */}
      <div className="grid grid-cols-[112px_360px] gap-2">

        <FormLabel className="text-right">備考</FormLabel>
        <WordTextBox {...register("filter.備考")} />

        <FormLabel className="text-right">明細件数</FormLabel>
        <Controller
          name="filter.明細件数"
          control={control}
          render={({ field: { name, value, onChange, onBlur, ref } }) => (
            <div className="flex items-center gap-2" onBlur={onBlur}>
              <NumericTextBox name={`${name}.from`} ref={ref}
                {...numericPropsOf("入荷一覧", "明細件数")}
                value={value?.from ?? ""}
                onChange={e => onChange({ ...value, from: e.target.value })} />
              <span>～</span>
              <NumericTextBox name={`${name}.to`}
                {...numericPropsOf("入荷一覧", "明細件数")}
                value={value?.to ?? ""}
                onChange={e => onChange({ ...value, to: e.target.value })} />
            </div>
          )}
        />

        <FormLabel className="text-right">入荷数量合計</FormLabel>
        <Controller
          name="filter.入荷数量合計"
          control={control}
          render={({ field: { name, value, onChange, onBlur, ref } }) => (
            <div className="flex items-center gap-2" onBlur={onBlur}>
              <NumericTextBox name={`${name}.from`} ref={ref}
                {...numericPropsOf("入荷一覧", "入荷数量合計")}
                value={value?.from ?? ""}
                onChange={e => onChange({ ...value, from: e.target.value })} />
              <span>～</span>
              <NumericTextBox name={`${name}.to`}
                {...numericPropsOf("入荷一覧", "入荷数量合計")}
                value={value?.to ?? ""}
                onChange={e => onChange({ ...value, to: e.target.value })} />
            </div>
          )}
        />
      </div>
    </div>
  )
}
