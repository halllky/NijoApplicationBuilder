/**
 * P201_入荷詳細 へ遷移するためのリンクURLを取得する関数
 */
export function getLinkUrlToP201入荷詳細(入荷ID?: string | null) {
  if (入荷ID) {
    return `/nyuka/edit/${入荷ID}`
  } else {
    return `/nyuka/new`
  }
}

/**
 * ルーティング定義
 */
export default [
  {
    path: "/nyuka/new",
    element: <P201_入荷詳細 mode="new" />,
    loader: () => {
      return Promise.resolve(createNew入荷詳細DisplayData())
    },
  },
  {
    path: "/nyuka/edit/:id",
    element: <P201_入荷詳細 mode="edit" />,
    loader: async ({ params }) => {
      const parameter = createNew入荷詳細画面初期表示ParameterDisplayData()
      parameter.入荷ID = params.id ?? ''

      const result = await callComplexPostEndpointAsync('入荷詳細画面初期表示', parameter, {
        ignoreConfirm: true,
      })
      if (result.type === 'ok') {
        return result.returnValue
      }
      console.error('入荷詳細画面初期表示エラー:', result)
      const msg = result.type === 'error' ? JSON.stringify(result.detail) : 'データの取得に失敗しました。'
      throw new Error(msg);
    }
  },
] satisfies ReactRouter.RouteObject[]

/**
 * P201 入荷詳細
 */
function P201_入荷詳細(props: {
  mode: 'new' | 'edit'
}) {

  const { revalidate } = useRevalidator()
  const navigate = ReactRouter.useNavigate()
  const [saving, setSaving] = React.useState(false)

  // react-hook-form のフォーム管理を利用
  const loaderData = ReactRouter.useLoaderData() as 入荷詳細DisplayData
  const formMethods = ReactHookForm.useForm<入荷詳細DisplayData>({
    defaultValues: loaderData,
  })
  const { register, control, getValues, setValue, reset } = formMethods
  const { isDirty } = formMethods.formState
  const { fields, append, remove } = ReactHookForm.useFieldArray({
    control,
    name: "入荷商品一覧"
  })

  // 以下の理由から useEffect によるリセットを行っている。
  // - 保存後の画面再読み込み（useRevalidator）の際、
  //   このコンポーネントのインスタンスは維持されるため、
  //   loaderDataが更新されても初期値が変わらない。
  // - ログインユーザー情報はこの時点でないと取得できない
  // - useFormの引数としてdefaultValuesを渡すだけだと
  //   isDirtyがtrueになってしまうため。
  const { loginUser } = useLoginLogout()
  React.useEffect(() => {
    const clone = window.structuredClone(loaderData)
    // 新規登録モードの場合
    if (props.mode === 'new') {
      clone.入荷日時 = dayjs().format('YYYY-MM-DD HH:mm:ss')
      clone.担当者.従業員番号 = loginUser?.従業員番号 ?? ''
      clone.担当者.氏名 = loginUser?.氏名 ?? ''
    }
    reset(clone)
  }, [loaderData, loginUser, reset])

  // 画面タイトル
  const [browserTitle, pageTitle] = React.useMemo(() => {
    if (props.mode === 'new') {
      return ["入荷登録", "入荷登録"]
    } else {
      const date = dayjs(loaderData.入荷日時).format('YYYY-MM-DD')
      return [
        `入荷 No.${loaderData.入荷ID} (${date})`,
        `入荷 No.${loaderData.入荷ID}`
      ]
    }
  }, [props.mode, loaderData])

  // 明細行追加処理
  const handleCreateNewItem = useEvent((newItem: 商品RefTarget) => {
    const newDetail = createNew入荷商品一覧DisplayData()
    newDetail.入荷明細ID = UUID.generate()
    newDetail.商品 = newItem
    newDetail.数量 = '1'
    newDetail.消費税区分 = newItem.消費税区分
    append(newDetail, { shouldFocus: false })
  })

  // 保存時処理
  const { replaceMessages, clearMessages } = DetailMessage.useSetter()
  const handleSave = useEvent(async () => {
    try {
      clearMessages()
      setSaving(true)

      if (props.mode === 'new') {
        const result = await callComplexPostEndpointAsync('入荷登録', formMethods.getValues())
        if (result.type === 'ok') {
          replaceMessages(result.detail)

          // 保存されたデータでリセットして isDirty を false にする。
          // reset による State 更新が反映され、ブロックが解除されるのを待ってから遷移する
          reset(result.returnValue)
          const waitAndNavigate = () => {
            if (formMethods.formState.isDirty) {
              window.setTimeout(waitAndNavigate, 10)
            } else {
              navigate(getLinkUrlToP201入荷詳細(result.returnValue.入荷ID))
            }
          }
          waitAndNavigate()

        } else if (result.type === 'canceled') {
          // 何もしない
        } else if (result.type === 'error') {
          replaceMessages(result.detail)
        }

      } else {
        const result = await callComplexPostEndpointAsync('入荷修正', formMethods.getValues())
        if (result.type === 'ok') {
          // forceReloadRef.current = true // 編集モードの場合は画面遷移しないのでリロードフラグは立てない
          replaceMessages(result.detail)
          revalidate()
        } else if (result.type === 'canceled') {
          // 何もしない
        } else if (result.type === 'error') {
          replaceMessages(result.detail)
        }
      }
    } finally {
      setSaving(false)
    }
  })

  return (
    <PageBase
      browserTitle={browserTitle}
      isDirty={isDirty}
      className="gap-2 px-8 py-2"
      contents={(
        <div className="max-h-full max-w-5xl flex flex-col gap-y-2">

            {/* ヘッダ */}
            <div className="flex items-start gap-1">
              <div className="flex-1 flex flex-wrap items-center gap-1 py-1">
                <h1 className="text-lg font-bold">
                  {pageTitle}
                </h1>

                <div className="flex gap-2 items-center">
                  <FormLabel className="basis-20 shrink-0 text-right">入荷日時</FormLabel>
                  <DateInput appearance="datetime" {...register("入荷日時")} />
                </div>

                <div className="flex gap-2 items-center">
                  <FormLabel className="basis-20 shrink-0 text-right">担当者</FormLabel>
                  <div className="flex gap-2">
                    <WordTextBox {...register("担当者.従業員番号")} className="w-32" />
                    {getValues("担当者.氏名")}
                  </div>
                </div>
              </div>

              <Button fill onClick={handleSave} loading={saving}>
                保存
              </Button>
            </div>

            <DescriptionTextArea
              {...register("備考")}
              placeholder="備考"
              className="min-h-16 max-h-28"
            />

            <div className="flex justify-between font-bold">
              <span className="select-none text-gray-600">
                明細
              </span>
            </div>

            {/* 明細欄 */}
            <DetailMessage.Of name="入荷商品一覧" control={control} />
            {fields.length === 0 && (
              <div className="select-none text-gray-500 py-1">
                明細がありません。
              </div>
            )}
            <div className="overflow-x-auto">
              <table className="min-w-max">
                <tbody>
                  {fields.map((field, index) => (
                    <React.Fragment key={field.id}>
                      <tr className="border-t border-gray-300 whitespace-nowrap">

                        {/* 商品 */}
                        <td className="p-1 align-middle font-bold">
                          <WordTextBox
                            {...register(`入荷商品一覧.${index}.商品.外部システム側ID`)}
                            maxLength={maxLengthOf("入荷詳細", `入荷商品一覧.${index}.商品.外部システム側ID`)}
                            className="w-32 shrink-0"
                          />
                        </td>
                        <td className="p-1 align-middle font-bold max-w-[16rem]">
                          <div
                            title={field.商品.商品名}
                            className="truncate"
                          >
                            {field.商品.商品名}
                          </div>
                        </td>

                        {/* 数量・単価 */}
                        <td className="p-1 align-middle">
                          <NumericTextBox
                            {...register(`入荷商品一覧.${index}.数量`)}
                            {...numericPropsOf("入荷詳細", `入荷商品一覧.${index}.数量`)}
                            className="w-24 text-right"
                          />
                        </td>
                        <td className="p-1 align-middle text-center">
                          <span className="mx-2">@</span>
                        </td>
                        <td className="p-1 align-middle">
                          <NumericTextBox
                            {...register(`入荷商品一覧.${index}.仕入単価_税抜`)}
                            {...numericPropsOf("入荷詳細", `入荷商品一覧.${index}.仕入単価_税抜`)}
                            className="w-32 text-right"
                          />
                        </td>
                        <td className="p-1 align-middle">
                          <ReactHookForm.Controller
                            name={`入荷商品一覧.${index}.消費税区分`}
                            control={control}
                            render={({ field: { value, ...restField } }) => (
                              <EnumSelection
                                type="消費税区分"
                                value={value}
                                {...restField}
                                className="w-32"
                              />
                            )}
                          />
                        </td>

                        {/* 備考 */}
                        <td className="p-1 align-middle">
                          <DescriptionTextArea
                            {...register(`入荷商品一覧.${index}.備考`)}
                            placeholder="備考"
                            className="w-64"
                          />
                        </td>

                        <td className="p-1 align-middle w-16 text-center">
                          <Button outline mini onClick={() => remove(index)}>
                            削除
                          </Button>
                        </td>
                      </tr>
                      <tr>
                        <td colSpan={8} className="p-0 border-none">
                          <DetailMessage.Of name={`入荷商品一覧.${index}`} includeDescendants control={control} />
                        </td>
                      </tr>
                    </React.Fragment>
                  ))}
                </tbody>
              </table>
            </div>

            {/* 新規明細行追加欄 */}
            <NewItemArea formMethods={formMethods} onCreate={handleCreateNewItem} />
          </div>
      )}
    />
  )
}

/**
 * 新規明細行追加エリア。
 * 商品と数量だけを選択する。金額調整などは追加後に行う。
 */
function NewItemArea(props: {
  formMethods: ReactHookForm.UseFormReturn<入荷詳細DisplayData>
  onCreate: (newItem: 商品RefTarget) => void
}) {
  const [searchCode, setSearchCode] = React.useState('')
  const [searchName, setSearchName] = React.useState('')
  const [errorMessage, setErrorMessage] = React.useState<string | null>(null)
  const [searching, setSearching] = React.useState(false)

  const handleSearchCode = async () => {
    if (!searchCode) return
    setSearching(true)
    setErrorMessage(null)
    try {
      const searchCondition = createNew商品SearchCondition()
      searchCondition.filter.外部システム側ID = searchCode
      searchCondition.take = '2' // ありえないが複数ヒットを考慮

      const result = await callComplexPostEndpointAsync('ref-to:商品', searchCondition, {
        ignoreConfirm: true,
      })
      if (result.type === 'ok') {
        if (result.returnValue.totalCount === 0) {
          setErrorMessage('該当する商品がありません')
        } else if (result.returnValue.totalCount === 1) {
          props.onCreate(result.returnValue.currentPageItems[0])
          setSearchCode('')
        } else {
          setErrorMessage('複数の商品がヒットしました。コードを確認してください。')
        }
      } else {
        setErrorMessage('検索エラーが発生しました')
      }
    } catch (e) {
      setErrorMessage('検索中にエラーが発生しました')
      console.error(e)
    } finally {
      setSearching(false)
    }
  }

  const handleSearchName = React.useCallback(async (keyword: string) => {
    const searchCondition = createNew商品SearchCondition()
    searchCondition.filter.商品名 = keyword

    const result = await callComplexPostEndpointAsync('ref-to:商品', searchCondition, {
      ignoreConfirm: true,
    })
    if (result.type === 'ok') {
      return result.returnValue.currentPageItems
    }
    return []
  }, [])

  return (
    <div className="border border-gray-300 p-2 bg-gray-50 flex flex-col gap-2">

      <div className="flex gap-x-8 gap-y-2 flex-col md:flex-row">

        <h2 className="self-start font-bold text-sm text-gray-600">
          新規明細行追加
        </h2>
        <div className="basis-2"></div>

        <div className="flex flex-col">
          <label className="text-xs text-gray-500">商品コード</label>
          <div className="flex gap-1">
            <WordTextBox
              value={searchCode}
              onChange={(e) => setSearchCode(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter') {
                  e.preventDefault()
                  handleSearchCode()
                }
              }}
              placeholder="商品コードで検索"
              className="w-32"
            />
            <Button outline onClick={handleSearchCode} loading={searching} disabled={!searchCode}>
              検索
            </Button>
          </div>
        </div>

        <div className="flex flex-col">
          <label className="text-xs text-gray-500">商品名</label>
          <AsyncComboBox
            value={searchName}
            onChange={(e) => setSearchName(e.target.value)}
            onSearch={handleSearchName}
            onSelectItem={(item) => {
              props.onCreate(item)
              setSearchName('')
            }}
            renderItem={(item) => (
              <div>
                <div className="text-sm font-bold">{item.商品名}</div>
                <div className="text-xs text-gray-500">{item.外部システム側ID}</div>
              </div>
            )}
            itemKey={(item) => item.商品SEQ ?? ''}
            className="w-64"
            placeholder="商品名で検索"
          />
        </div>

      </div>
      {errorMessage && (
        <div className="text-red-600 text-sm">{errorMessage}</div>
      )}
    </div>
  )
}
