import React from "react"
import * as EG2 from "@nijo/ui-components/layout/EditableGrid2"
import * as AutoGenerated from "../../__autoGenerated/enum-defs"

/**
 * 列挙型セル用のエディタをキャッシュして返す。
 * 列挙型の種類の集合は閉じているため（消費税区分・売上明細区分）、型名をキーにキャッシュする。
 */
const enumEditorCache = new Map<keyof AutoGenerated.EnumTypeMap, EG2.EditableGridCellEditor>()

export function getEnumCellEditor<T extends keyof AutoGenerated.EnumTypeMap>(type: T): EG2.EditableGridCellEditor {
  const cached = enumEditorCache.get(type)
  if (cached) return cached

  const options = AutoGenerated.EnumValueMap[type]()

  const Editor: EG2.EditableGridCellEditor = React.forwardRef(function EnumCellEditor({ style, isEditing, requestCommit, requestCancel }, ref) {
    const selectRef = React.useRef<HTMLSelectElement>(null)
    const [value, setValue] = React.useState('')

    const handleChange: React.ChangeEventHandler<HTMLSelectElement> = e => {
      requestCommit(e.target.value)
    }
    const handleClick: React.MouseEventHandler<HTMLSelectElement> = () => {
      if (isEditing) requestCommit(selectRef.current?.value ?? '')
    }
    const handleKeyDown: React.KeyboardEventHandler<HTMLSelectElement> = e => {
      if (isEditing && e.key === 'Escape') {
        requestCancel()
        e.preventDefault()
      }
    }

    React.useImperativeHandle(ref, () => ({
      getCurrentValue: () => selectRef.current?.value ?? '',
      setValueAndSelectAll: (v, timing) => {
        setValue(v)
        setTimeout(() => {
          selectRef.current?.focus()
          if (timing === 'edit-start') selectRef.current?.showPicker?.()
        }, 0)
      },
      getDomElement: () => selectRef.current,
    }), [])

    return (
      <div style={style}>
        <select
          ref={selectRef}
          value={value}
          onChange={handleChange}
          onClick={handleClick}
          onKeyDown={handleKeyDown}
          className="w-full h-full border border-black outline-none bg-white"
        >
          <option value=""></option>
          {options.map(o => (
            <option key={o} value={o}>{o}</option>
          ))}
        </select>
      </div>
    )
  })

  enumEditorCache.set(type, Editor)
  return Editor
}

/** onCellKeyDown 用: Enter / Alt+↑↓ でドロップダウンの編集を開始する */
export function startEnumEditOnKeyDown(args: { event: React.KeyboardEvent, requestEditStart: () => void }) {
  const alt = args.event.altKey || args.event.metaKey
  const upDown = args.event.key === 'ArrowUp' || args.event.key === 'ArrowDown'
  if (args.event.key === 'Enter' || (alt && upDown)) {
    args.requestEditStart()
    args.event.preventDefault()
  }
}
