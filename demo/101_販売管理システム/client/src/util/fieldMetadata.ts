import { QueryModelType, StructureModelType } from "../__autoGenerated"
import { MetadataForPage } from "../__autoGenerated/util/metadata-for-page"
import { NumericTextBoxProps } from "../input/NumericTextBox"

/**
 * 自動生成されたメタデータから、指定した集約配下のフィールドの定義を取得する。
 * fieldPath は react-hook-form のフィールド名をそのまま渡せる
 * （先頭の "filter." と、配列インデックス（半角数値のみの部分）は自動で読み飛ばす）。
 * 途中に外部参照(ref-to)を挟む場合は参照先を辿る。
 */
export function getFieldMetadata(
  rootAggregate: QueryModelType | StructureModelType,
  fieldPath: string,
): MetadataForPage.StructureMetadataMember {
  const allMetadata = MetadataForPage.getAll() as { [key: string]: MetadataForPage.RootAggregateMetadata }
  const rootMetadata = allMetadata[rootAggregate]

  const parts = fieldPath.split('.')
  const filteredParts: string[] = []
  for (let i = 0; i < parts.length; i++) {
    const part = parts[i]
    // 検索条件オブジェクトの場合は最初が "filter" で始まる
    if (i === 0 && part === "filter") continue;
    // 半角数値のみから構成される部分は配列インデックスなので除外する
    if (/^\d+$/.test(part)) continue;
    filteredParts.push(part)
  }

  const trace: (MetadataForPage.StructureMetadataMember | MetadataForPage.RootAggregateMetadata)[] = [rootMetadata]
  while (true) {
    const part = filteredParts.shift()
    if (!part) break

    const current = trace[trace.length - 1]
    if (!('members' in current)
      || typeof current.members !== 'object'
      || current.members === null
      || !(part in current.members)) {
      console.error(`getFieldMetadata - ${fieldPath}`, { rootAggregate, filteredParts, trace, part, current })
      throw new Error(`フィールドのメタデータが見つかりません: ${fieldPath}`)
    }

    const next = current.members[part]
    trace.push(next)

    // いま見つけたメンバーが外部参照であり、かつまだ辿るべき部分が残っている場合、
    // 参照先のメタデータを取得してそこから辿る
    if (filteredParts.length > 0 && next.type === "ref-to") {
      trace.push(getRefTo(allMetadata, next.refTo))
    }
  }

  return trace[trace.length - 1] as MetadataForPage.StructureMetadataMember
}

/** 参照先のメタデータを取得する。見つからない場合は例外を投げる */
function getRefTo(
  allMetadata: { [key: string]: MetadataForPage.RootAggregateMetadata },
  refTo: `ref-to:${string}`,
): MetadataForPage.StructureMetadata {
  // 参照先が子孫集約の場合はスラッシュ区切りになっている
  const [refToRoot, ...refToDescendantPath] = refTo.slice('ref-to:'.length).split('/')
  const trace: {}[] = [allMetadata[refToRoot]]

  for (const part of refToDescendantPath) {
    const current = trace[trace.length - 1]
    if (!('members' in current)
      || typeof current.members !== 'object'
      || current.members === null
      || !(part in current.members)) {
      console.error(`getRefTo - ${refTo}`, { trace, part })
      throw new Error(`参照先のメタデータが見つかりません: ${refTo}`)
    }
    const next = current[part as keyof typeof current] as MetadataForPage.StructureMetadata
    trace.push(next)
  }

  return trace[trace.length - 1] as MetadataForPage.StructureMetadata
}

/**
 * 数値項目のメタデータから NumericTextBox の桁数・単位の props を組み立てる。
 * 金額項目なら "円"、数量なら "個" のサフィックスと3桁カンマ区切りが付く。
 */
export function numericPropsOf(
  rootAggregate: QueryModelType | StructureModelType,
  fieldPath: string,
): Pick<NumericTextBoxProps, "integerDigit" | "decimalDigit" | "suffix" | "commaSeparated"> {
  const fieldMetadata = getFieldMetadata(rootAggregate, fieldPath)
  if (!('type' in fieldMetadata)) {
    throw new Error(`数値項目ではありません: ${fieldPath}`)
  }

  let decimalDigit: number | undefined = undefined
  if (fieldMetadata.decimalPlace !== undefined) {
    decimalDigit = fieldMetadata.decimalPlace
  } else if (fieldMetadata.type === "decimal") {
    decimalDigit = 7
  } else if (fieldMetadata.type === "int" || fieldMetadata.type === "sequence" || fieldMetadata.type === "year") {
    decimalDigit = 0
  }

  let integerDigit: number | undefined = undefined
  if (fieldMetadata.totalDigit !== undefined) {
    integerDigit = fieldMetadata.totalDigit - (decimalDigit || 0)
  } else if (fieldMetadata.type === "year") {
    integerDigit = 4
  } else {
    integerDigit = 18 - (decimalDigit || 0)
  }

  let suffix: string | undefined = undefined
  let commaSeparated: boolean = false
  if (fieldMetadata.isCurrency) {
    suffix = "円"
    commaSeparated = true
  } else if (fieldMetadata.isQuantity) {
    suffix = "個"
    commaSeparated = true
  }

  return { integerDigit, decimalDigit, suffix, commaSeparated }
}

/** 単語項目のメタデータから最大文字数を取得する。未設定なら undefined。 */
export function maxLengthOf(
  rootAggregate: QueryModelType | StructureModelType,
  fieldPath: string,
): number | undefined {
  const fieldMetadata = getFieldMetadata(rootAggregate, fieldPath)
  return 'customMaxLength' in fieldMetadata ? fieldMetadata.customMaxLength : undefined
}
